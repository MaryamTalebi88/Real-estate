const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const stored = typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_KEY) : null
    return stored === 'fa' || stored === 'en' ? stored : 'en'
  })

  const dir = lang === 'fa' ? 'rtl' : 'ltr'

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = dir
    window.localStorage.setItem(STORAGE_KEY, lang)
  }, [lang, dir])

  const setLang = useCallback((next) => setLangState(next === 'fa' ? 'fa' : 'en'), [])

  const t = useCallback(
    (key, fallback) => DICT[lang]?.[key] ?? DICT.en[key] ?? fallback ?? key,
    [lang],
  )

  const pick = useCallback(
    (en, fa) => (lang === 'fa' ? fa || en : en || fa) ?? '',
    [lang],
  )

  const value = useMemo(
    () => ({ lang, dir, setLang, t, pick, isRtl: dir === 'rtl' }),
    [lang, dir, setLang, t, pick],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
